import fs from "fs";
import path from "path";
import { execSync } from "child_process";

const ROOT_DIR = process.cwd();
const AUDIT_FILE = path.join(ROOT_DIR, "PAGE_AUDIT.md");

function getGitLastEdited(filePath) {
  try {
    const relativePath = path.relative(ROOT_DIR, filePath);
    const output = execSync(
      `git log -1 --format="%cd" --date=short -- "${relativePath}"`,
      {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      },
    ).trim();
    return output || "Uncommitted";
  } catch {
    return "Unknown";
  }
}

function scanDirectory(dirPath, extensionRegex) {
  const results = [];
  if (!fs.existsSync(dirPath)) return results;

  function recurse(current) {
    const entries = fs.readdirSync(current, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(current, entry.name);
      if (entry.isDirectory()) {
        if (
          entry.name !== "node_modules" &&
          entry.name !== ".next" &&
          entry.name !== ".git"
        ) {
          recurse(fullPath);
        }
      } else if (entry.isFile() && extensionRegex.test(entry.name)) {
        results.push(fullPath);
      }
    }
  }

  recurse(dirPath);
  return results;
}

function generateMarkdownTable(files, columns) {
  if (files.length === 0) return "_No files found._\n";

  let markdown = `| ${columns.join(" | ")} |\n`;
  markdown += `| ${columns.map(() => "---").join(" | ")} |\n`;

  for (const file of files) {
    const relativePath = path.relative(ROOT_DIR, file).replace(/\\/g, "/");
    const lastEdited = getGitLastEdited(file);
    markdown += `| \`${relativePath}\` | STABLE | ${lastEdited} |\n`;
  }

  return markdown;
}

function main() {
  console.log("Scanning Onesimos codebase for page and component audit...");

  const appFiles = scanDirectory(
    path.join(ROOT_DIR, "app"),
    /\.(tsx|ts|js|jsx)$/,
  );
  const componentFiles = scanDirectory(
    path.join(ROOT_DIR, "components"),
    /\.(tsx|ts|js|jsx)$/,
  );
  const libFiles = scanDirectory(
    path.join(ROOT_DIR, "lib"),
    /\.(tsx|ts|js|jsx)$/,
  );
  const mobileFiles = scanDirectory(
    path.join(ROOT_DIR, "mobile"),
    /\.(tsx|ts|js|jsx|json)$/,
  );

  const routes = appFiles.filter(
    (f) => f.includes("page.") || f.includes("route."),
  );
  const layoutsAndGlobals = appFiles.filter(
    (f) => !f.includes("page.") && !f.includes("route."),
  );

  const timestamp =
    new Date().toISOString().replace("T", " ").substring(0, 19) + " UTC";

  const content = `# ONESIMOS : PAGE AND COMPONENT AUDIT

**Automated Scan Timestamp:** ${timestamp}
**Repo Root:** \`${ROOT_DIR}\`

This file is automatically generated and updated via \`node scripts/generate-page-audit.mjs\` or \`npm run audit:pages\`.

---

## 1. ROUTES AND API ENDPOINTS (Next.js App Router)

${generateMarkdownTable(routes, ["File Path", "Status", "Last Git Commit"])}

---

## 2. APP LAYOUTS, GLOBALS, AND SHELLS

${generateMarkdownTable(layoutsAndGlobals, ["File Path", "Status", "Last Git Commit"])}

---

## 3. SHARED COMPONENTS

${generateMarkdownTable(componentFiles, ["Component Path", "Status", "Last Git Commit"])}

---

## 4. SHARED LIBRARIES AND UTILITIES

${generateMarkdownTable(libFiles, ["Module Path", "Status", "Last Git Commit"])}

---

## 5. EXPO MOBILE WRAPPER

${generateMarkdownTable(mobileFiles, ["Mobile Path", "Status", "Last Git Commit"])}

---

## 6. AUDIT VERIFICATION CHECKLIST

- [ ] Run \`npm run build\` locally before committing.
- [ ] Ensure no em dashes or en dashes exist in copy or comments.
- [ ] Confirm Pip Companion remains free-floating with no yellow rectangle.
- [ ] Confirm Letter Sounds in Phonics Lab remains 100% free.
- [ ] Confirm Free Monthly Story Limit is set to 5 in \`lib/sessionBudget.ts\`.
- [ ] Ensure non-admin parents cannot access the test quota reset button.
- [ ] Verify Supabase and Paystack live configurations are active.
`;

  fs.writeFileSync(AUDIT_FILE, content, "utf8");
  console.log(`Successfully updated PAGE_AUDIT.md at ${AUDIT_FILE}`);
}

main();
